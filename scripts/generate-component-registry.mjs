// INO-317: generates web/src/app/pages/docs/components/generated/component-registry.ts — a
// slug -> component-class lookup table the /docs/components/:slug live-example renderer uses to
// dynamically mount the real component (via NgComponentOutlet). Walks
// web/src/app/components/*/ino-*.component.ts the same way
// scripts/generate-design-system-manifest.mjs does, so the registry always matches the manifest.
// Generated — do not hand-edit. Re-run after adding or renaming a component:
// `node scripts/generate-component-registry.mjs`.
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const componentsDir = new URL('web/src/app/components/', root);
const outUrl = new URL(
  'web/src/app/pages/docs/components/generated/component-registry.ts',
  root,
);

const entries = [];
for (const dirName of readdirSync(componentsDir).sort()) {
  if (!statSync(new URL(dirName, componentsDir)).isDirectory()) continue;
  const dirUrl = new URL(dirName + '/', componentsDir);
  const tsPath = new URL(`ino-${dirName}.component.ts`, dirUrl);
  let source;
  try {
    source = readFileSync(tsPath, 'utf8');
  } catch {
    continue; // directory without a matching ino-<name>.component.ts — not a component
  }
  const classMatch = source.match(/export class (\w+)/);
  if (!classMatch) continue;
  entries.push({
    slug: dirName,
    className: classMatch[1],
    // Relative from web/src/app/pages/docs/components/generated/ to
    // web/src/app/components/<dirName>/ino-<dirName>.component
    importPath: `../../../../components/${dirName}/ino-${dirName}.component`,
  });
}

const importLines = entries
  .map((e) => `import { ${e.className} } from '${e.importPath}';`)
  .join('\n');
const registryLines = entries.map((e) => `  '${e.slug}': ${e.className},`).join('\n');

const output = `// Generated by scripts/generate-component-registry.mjs — do not hand-edit.
// Re-run after adding or renaming a component: \`node scripts/generate-component-registry.mjs\`.
// Slug -> component class lookup for the /docs/components/:slug live-example renderer.
import { Type } from '@angular/core';

${importLines}

export const COMPONENT_REGISTRY: Record<string, Type<any>> = {
${registryLines}
};
`;

writeFileSync(outUrl, output);
console.log(`wrote web/src/app/pages/docs/components/generated/component-registry.ts (${entries.length} components)`);
